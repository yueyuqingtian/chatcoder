export function translate(key: string, lang: Language, params?: Record<string, string | number>): string {
  const entry = DICT[key];
  let res = entry ? (lang === "en" ? entry[1] : entry[0]) : key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      res = res.replaceAll(`{${k}}`, String(v));
    }
  }
  return res;
}

export function useI18n() {
  const language = useUiStore((s) => s.language);
  return {
    language,
    t: (key: string, params?: Record<string, string | number>) => translate(key, language, params),
  };
}
