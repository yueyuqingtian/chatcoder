import assert from "node:assert/strict";
import { isMessageAppend, markMessageAppend, indexMessageAppend, hasMessageId } from "../src/utils/messageChanges.ts";
const first = [1];
const second = markMessageAppend(first, [1, 2]);
const third = markMessageAppend(second, [1, 2, 3]);
assert.equal(isMessageAppend(first, third), true);
assert.equal(isMessageAppend(second, third), true);
const fork = markMessageAppend(first, [1, 4]);
const forkTail = markMessageAppend(fork, [1, 4, 5]);
assert.equal(isMessageAppend(second, forkTail), false);
assert.equal(isMessageAppend(second, [1, 2, 3]), false);
console.log("可信追加与分叉安全回归通过");
const a = [{ id: 1 }];
const b = indexMessageAppend(a, [...a, { id: 2 }]);
assert.equal(hasMessageId(b, 2), true);
assert.equal(hasMessageId(a, 2), false);
const c = indexMessageAppend(a, [...a, { id: 3 }]);
assert.equal(hasMessageId(c, 2), false);
assert.equal(hasMessageId(c, 3), true);
